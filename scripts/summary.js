// Build the tables in results/summary.md from the recorded runs. Refuses files
// without a stamp, and runs of one set made by different harness versions.
//   node scripts/summary.js
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url).pathname;
const NAMES = ['ifs', 'cerbos', 'spicedb'];
const read = (p) => JSON.parse(readFileSync(`${root}${p}`, 'utf8'));

function load(dir, pattern) {
  if (!existsSync(`${root}${dir}`)) return [];
  const files = readdirSync(`${root}${dir}`).filter((f) => pattern.test(f)).sort();
  const runs = files.map((f) => ({ file: `${dir}/${f}`, ...read(`${dir}/${f}`) }));
  for (const r of runs) if (!r.stamp?.harnessHash) throw new Error(`${r.file} has no stamp`);
  const hashes = new Set(runs.map((r) => r.stamp.harnessHash));
  if (hashes.size > 1) throw new Error(`${dir}: runs from ${hashes.size} harness versions: ${[...hashes]}`);
  return runs;
}

const med = (xs) => {
  const s = [...xs].sort((a, b) => a - b);
  return s.length % 2 ? s[(s.length - 1) / 2] : (s[s.length / 2 - 1] + s[s.length / 2]) / 2;
};
const fmt = (v) => (v >= 100 ? v.toFixed(0) : v >= 10 ? v.toFixed(1) : v.toFixed(2));
const lines = [];
const p = (s = '') => lines.push(s);

// Per step
const correctness = load('results/steps', /-correctness\.json$/);
const checks = load('results/steps', /-check\.json$/);
const lists = load('results/steps', /-list\.json$/);

p('# Summary');
p();
p('Generated by `node scripts/summary.js` from the JSON files in `results/`.');
p();
p('## Correctness at every step (fixture/expected.csv)');
p();
p('| Step | ifs | cerbos | spicedb |');
p('| --- | --- | --- | --- |');
for (const r of correctness) {
  const cells = NAMES.map((n) => {
    const a = r.approaches[n];
    return a.mismatches === 0 ? `${a.checks} checks + ${a.lists} lists match` : `${a.mismatches} mismatches`;
  });
  p(`| ${r.stamp.step} | ${cells.join(' | ')} |`);
}
p();
p('## Single check per step, 10,000 documents, ms (p50 / p95 / p99)');
p();
p('| Step | ifs | cerbos | spicedb | errors | disagreements | load at start |');
p('| --- | --- | --- | --- | --- | --- | --- |');
for (const r of checks) {
  const cells = NAMES.map((n) => {
    const l = r.approaches[n].latencyMs;
    return `${fmt(l.p50)} / ${fmt(l.p95)} / ${fmt(l.p99)}`;
  });
  const errs = NAMES.map((n) => `${n} ${r.approaches[n].errors?.count ?? 0}`).join(', ');
  p(`| ${r.stamp.step} | ${cells.join(' | ')} | ${errs} | ${r.disagreements.count} | ${r.stamp.loadavgAtStart[0]} |`);
}
p();
p('## List per step, median ms (visible documents)');
p();
p('| Step | Docs | Profile | ifs | cerbos | spicedb | agree |');
p('| --- | --- | --- | --- | --- | --- | --- |');
for (const r of lists) {
  for (const run of r.runs) {
    for (const [profile, x] of Object.entries(run.profiles)) {
      const cells = NAMES.map((n) => fmt(x.latencyMs[n].p50));
      p(`| ${r.stamp.step} | ${run.docs} | ${profile} (${x.visible.ifs}) | ${cells.join(' | ')} | ${x.agree} |`);
    }
  }
}

const caches = load('results/steps', /-spicedb-list-cache\.json$/);
if (caches.length) {
  p();
  p('## SpiceDB list per step, 10,000 documents: first call in a new 5 s window / same revision again, median ms');
  p();
  p('| Step | admin | member | contractor |');
  p('| --- | --- | --- | --- |');
  caches.forEach((r, i) => {
    const c = (k) => `${fmt(r.profiles[k].coldMs.p50)} / ${fmt(r.profiles[k].warmMs.p50)} (${r.profiles[k].visible} visible)`;
    p(`| ${i + 1} | ${c('admin')} | ${c('member')} | ${c('contractor')} |`);
  });
}

// Final
const fLists = load('results/final', /^list-\d+\.json$/);
for (const [label, pattern] of [
  ['every sample a new random triple', /^check-\d+\.json$/],
  ['samples drawn from 100 repeating triples', /^check-hot-\d+\.json$/],
]) {
  const fChecks = load('results/final', pattern);
  if (!fChecks.length) continue;
  p();
  p(`## Step 4, single check, 10,000 documents, ${label}: ${fChecks.length} runs of ${fChecks[0].stamp.samples} samples`);
  p();
  p('Median across runs of each statistic, with the range across runs in brackets. ms.');
  p();
  p('| Design | p50 | p95 | p99 | max | errors (all runs) |');
  p('| --- | --- | --- | --- | --- | --- |');
  for (const n of NAMES) {
    const stat = (k) => {
      const xs = fChecks.map((r) => r.approaches[n].latencyMs[k]);
      return `${fmt(med(xs))} [${fmt(Math.min(...xs))}-${fmt(Math.max(...xs))}]`;
    };
    const errs = fChecks.reduce((s, r) => s + (r.approaches[n].errors?.count ?? 0), 0);
    p(`| ${n} | ${stat('p50')} | ${stat('p95')} | ${stat('p99')} | ${stat('max')} | ${errs} |`);
  }
  const srv = fChecks.map((r) => r.cerbosServerHandlingMs).filter(Boolean);
  if (srv.length) {
    p();
    p(`Cerbos's own handling time from its log, median across runs: p50 ${fmt(med(srv.map((s) => s.p50)))} ms, p99 ${fmt(med(srv.map((s) => s.p99)))} ms.`);
  }
  p();
  p(`Disagreements between designs: ${fChecks.map((r) => r.disagreements.count).join(', ')}. Load average at start: ${fChecks.map((r) => r.stamp.loadavgAtStart[0]).join(', ')}.`);
}
if (fLists.length) {
  p();
  p(`## Step 4, list, ${fLists.length} runs of ${fLists[0].stamp.iters} iterations: median of the run medians, ms`);
  p();
  p('| Docs | Profile (visible) | ifs | cerbos | spicedb | spicedb / ifs | spicedb / cerbos |');
  p('| --- | --- | --- | --- | --- | --- | --- |');
  for (let i = 0; i < fLists[0].runs.length; i++) {
    const docs = fLists[0].runs[i].docs;
    for (const profile of Object.keys(fLists[0].runs[i].profiles)) {
      const m = Object.fromEntries(NAMES.map((n) => [n, med(fLists.map((r) => r.runs[i].profiles[profile].latencyMs[n].p50))]));
      const vis = fLists[0].runs[i].profiles[profile].visible.ifs;
      const agree = fLists.every((r) => r.runs[i].profiles[profile].agree);
      p(`| ${docs} | ${profile} (${vis})${agree ? '' : ' DISAGREE'} | ${NAMES.map((n) => fmt(m[n])).join(' | ')} | ${(m.spicedb / m.ifs).toFixed(0)}x | ${(m.spicedb / m.cerbos).toFixed(1)}x |`);
    }
  }
}
if (existsSync(`${root}results/final/floor.json`)) {
  const f = read('results/final/floor.json');
  p();
  p('## The call itself (results/final/floor.json), ms');
  p();
  p('| Call | p50 | p95 | p99 |');
  p('| --- | --- | --- | --- |');
  for (const [n, l] of Object.entries(f.latencyMs)) p(`| ${n} | ${fmt(l.p50)} | ${fmt(l.p95)} | ${fmt(l.p99)} |`);
}
if (existsSync(`${root}results/final/lookup-pages.json`)) {
  const f = read('results/final/lookup-pages.json');
  p();
  p('## LookupResources page size, 10,000 documents (results/final/lookup-pages.json), median ms');
  p();
  p('| Profile (visible) | no limit | 1000 | 100 |');
  p('| --- | --- | --- | --- |');
  for (const [profile, x] of Object.entries(f.profiles)) {
    const c = (k) => `${fmt(x.pages[k].latencyMs.p50)} (${x.pages[k].requests} calls)`;
    p(`| ${profile} (${x.pages[0].size}) | ${c(0)} | ${c(1000)} | ${c(100)} |`);
  }
}
if (existsSync(`${root}results/final/spicedb-page.json`)) {
  const f = read('results/final/spicedb-page.json');
  p();
  p('## SpiceDB, first 50 visible documents, 10,000 documents (results/final/spicedb-page.json), median ms');
  p();
  p('| Profile | LookupResources, then first 50 | CheckBulkPermissions over candidates | same 50? |');
  p('| --- | --- | --- | --- |');
  for (const [profile, x] of Object.entries(f.profiles)) {
    p(
      `| ${profile} | ${fmt(x.lookupAllThenFirst50.latencyMs.p50)} | ${fmt(x.bulkCheckCandidates.latencyMs.p50)} (${x.bulkCheckCandidates.scanned} candidates, ${x.bulkCheckCandidates.requests} calls) | ${x.agree} |`,
    );
  }
}
if (existsSync(`${root}results/final/spicedb-list-cache.json`)) {
  const f = read('results/final/spicedb-list-cache.json');
  p();
  p('## SpiceDB list, cold and warm cache, 10,000 documents (results/final/spicedb-list-cache.json), median ms');
  p();
  p('| Profile (visible) | first call in a new 5 s window | same revision again |');
  p('| --- | --- | --- |');
  for (const [profile, x] of Object.entries(f.profiles)) {
    p(`| ${profile} (${x.visible}) | ${fmt(x.coldMs.p50)} [${fmt(x.coldMs.min)}-${fmt(x.coldMs.max)}] | ${fmt(x.warmMs.p50)} [${fmt(x.warmMs.min)}-${fmt(x.warmMs.max)}] |`);
  }
}
if (existsSync(`${root}results/final/variant-cerbos-in-subquery.json`)) {
  const f = read('results/final/variant-cerbos-in-subquery.json');
  p();
  p('## Variant: Cerbos adapter with an uncorrelated IN subquery for shares (results/final/variant-cerbos-in-subquery.json), median ms');
  p();
  p('| Profile (visible) | ifs | cerbos |');
  p('| --- | --- | --- |');
  for (const [profile, x] of Object.entries(f.runs[0].profiles)) {
    p(`| ${profile} (${x.visible.ifs})${x.agree ? '' : ' DISAGREE'} | ${fmt(x.latencyMs.ifs.p50)} | ${fmt(x.latencyMs.cerbos.p50)} |`);
  }
}
const d = read('results/diffstat.json');
p();
p('## Code changed per step (results/diffstat.json): files, lines added + deleted');
p();
p('| Step | shared data model | ifs | cerbos | spicedb |');
p('| --- | --- | --- | --- | --- |');
for (const [step, s] of Object.entries(d.steps)) {
  const c = (x) => `${x.files} files, ${x.changed} lines`;
  p(`| ${step} | ${c(s.data)} | ${c(s.ifs)} | ${c(s.cerbos)} | ${c(s.spicedb)} |`);
}
const total = Object.fromEntries(NAMES.map((n) => [n, Object.values(d.steps).reduce((t, s) => t + s[n].changed, 0)]));
p(`| total | | ${total.ifs} lines | ${total.cerbos} lines | ${total.spicedb} lines |`);
p();
writeFileSync(`${root}results/summary.md`, lines.join('\n'));
console.log(lines.join('\n'));
